import type { NextConfig } from "next";

// ============================================================
// إعداد Next.js — تهيئة النشر خارج Vercel
// ============================================================
// لا تغيّر هذه التهيئة أي شيء في معمارية الأمان:
//   • البوابة تبقى في src/proxy.ts وحدها.
//   • مسارات /api/* تبقى كما هي.
//   • كلمة المرور تبقى في البيئة ولا تدخل أي حزمة.
//
// ما تُضيفه: منع الوسائط المشتركة (CDN/وسيط عكسي) من تخزين الصفحات
// المحمية. السبب مُختبَر عمليًا: صفحات الموقع تُبنى مسبقًا (prerender)
// ويُرسل لها Next ترويسة `Cache-Control: s-maxage=31536000` بلا
// `Vary: Cookie`. أي وسيط تخزين مشترك أمام الخادم قد يخزّن HTML
// المحمي ثم يقدّمه لزائر بلا كوكي — لأن البوابة تتحقّق على الخادم
// قبل الرد، ولا علاقة لها بترويسات التخزين التي يراها الوسيط.
//
// القاعدة أدناه تُجبر ردود HTML ومسارات الـ API على:
//     Cache-Control: private, no-store, max-age=0
// أي: لا يخزّنها أي وسيط مشترك إطلاقًا.
//
// وتُستثنى أصول Next.js الثابتة (`/_next/static`، `/_next/image`)
// وفافيكون، فتبقى قابلة للتخزين بلا حدود
// (`public, max-age=31536000, immutable`) — فلا خسارة في الأداء.
//
// ثمن بسيط: ذاكرة الجلب المسبق (prefetch) في المتصفح لا يُعاد
// استخدامها بين التنقّلات، فيزداد عدد طلبات RSC قليلًا.
//
// إن فُضِّل ضبط التخزين على مستوى المزوّد بدلًا من هنا (مثلًا قاعدة
// «لا تخزّن HTML» على Cloudflare)، يمكن حذف هذا المقطع — التفصيل في
// docs/deployment-node.md.
// ============================================================

const nextConfig: NextConfig = {
  async headers() {
    return [
      {
        source: "/:path((?!_next/static|_next/image|favicon.ico).*)",
        headers: [{ key: "Cache-Control", value: "private, no-store, max-age=0" }],
      },
    ];
  },
};

export default nextConfig;
