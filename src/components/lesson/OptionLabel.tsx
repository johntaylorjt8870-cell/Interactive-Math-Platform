import MathExpr from "../math/MathExpr";
import RichText from "../bidi/RichText";

// ============================================================
// لصاقة خيار في سؤال اختياري — Option label
// ============================================================
// خيارات أسئلة الكتاب تأتي على ثلاثة أشكال:
//   1) رياضيات خام بصيغة LaTeX (مثل \frac{1}{3}) → تُعرض بـ <MathExpr>.
//   2) نص عربي قد تتخلله رياضيات مغلفة بـ $...$ → تُعرض بـ <RichText>
//      (تعزل الرياضيات LTR والعربي RTL تلقائيًا).
//   3) رياضيات مغلفة بـ $...$ → <RichText> كذلك.
// القاعدة: إن حمل الخيار رياضيات مغلفة أو أي حرف عربي فهو نص غني،
// وإلا فهو حقل رياضيات خام. هكذا تبقى خيارات الدروس القديمة (رياضيات
// خام) كما هي، وتستطيع أسئلة الكتاب النصية الظهور بألفاظها الأصلية.
// ============================================================
export default function OptionLabel({ value }: { value: string }) {
  const rich = value.includes("$") || /[\u0600-\u06FF]/.test(value);
  return rich ? <RichText text={value} /> : <MathExpr value={value} />;
}
